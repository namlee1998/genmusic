const DEFAULT_SCRIPT = {};

/** Resolve the script for a scenario+role (never throws). */
function getScript(scenario, role) {
  void scenario;
  const byScenario = MOCK_SCRIPTS.happy_path || {};
  return byScenario[role] || DEFAULT_SCRIPT;
}

