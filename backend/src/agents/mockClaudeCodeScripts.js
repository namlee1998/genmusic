const PO_ASKS = {
  asks: {
    questions: [
      {
        question: 'Which Google account types should be allowed to sign in?',
        header: 'Account scope',
        options: [
          { label: 'Any Google account', description: 'Personal + workspace accounts' },
          { label: 'Workspace only', description: 'Restrict to a verified company domain' },
        ],
        multiSelect: false,
      },
    ],
  },
  // Fold the chosen answer into the PRD assumptions.
  applyAnswers(answers, context) {
    const choice = Array.isArray(answers) && answers.length ? answers[0] : null;
    context.po_clarification = {
      asked: true,
      answer: choice || 'Any Google account (default assumption — no answer given)',
      defaulted: !choice,
    };
    return context;
  },
};

